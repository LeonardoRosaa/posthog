const SAVE_FAILED_MESSAGE = "Couldn't save your edit. Try again."

export const REMOVED_MESSAGES_LOADING = 'Counting the messages after this one'

/**
 * What the editor says about the messages saving removes. Nothing when none would go, or when the count is unknown
 * because the preview failed: a wrong count would be worse than none.
 */
export const PROJECT_CHANGES_STAY_NOTICE =
    'Changes they made to your project, such as new insights or dashboards, stay as they are.'

/** The editor's notice: what saving removes, and that project changes those messages made are kept. */
export function editSaveNotice(count: number | null, changesProject: boolean): string | null {
    const removed = removedMessagesNotice(count)
    return removed && changesProject ? `${removed} ${PROJECT_CHANGES_STAY_NOTICE}` : removed
}

export function removedMessagesNotice(count: number | null): string | null {
    if (count === null || count === 0) {
        return null
    }
    return count === 1
        ? 'Saving removes the message after this one.'
        : `Saving removes the ${count} messages after this one.`
}

/** The server's reason when it refused the edit, or a generic retry message for a network or unknown failure. */
export function editSaveErrorMessage(error: unknown): string {
    const detail = error !== null && typeof error === 'object' ? (error as { detail?: unknown }).detail : undefined
    return typeof detail === 'string' && detail ? detail : SAVE_FAILED_MESSAGE
}

// pinned: analytics event name, renaming breaks dashboards. The backend captures the started and saved events.
export const MESSAGE_EDIT_CANCELLED_EVENT = 'posthog_ai_message_edit_cancelled'

/** How an editor closed without saving: its Cancel button, Escape, or the chat going away with it open. */
export type MessageEditCancelSource = 'button' | 'escape' | 'left_page'

interface CancelledEditState {
    taskId: string | null
    runId: string | null
    removedMessageCount: number | null
    removedTurnsChangeProject: boolean | null
    threadItems: ThreadItem[]
    itemId: string
}

// Counts and flags only: the message text and its context never go into the event.
function captureEditCancelled(state: CancelledEditState, source: MessageEditCancelSource): void {
    posthog.capture(MESSAGE_EDIT_CANCELLED_EVENT, {
        task_id: state.taskId,
        run_id: state.runId,
        removed_message_count: state.removedMessageCount,
        removed_turns_change_project: state.removedTurnsChangeProject,
        position_from_end: positionFromEnd(state.threadItems, state.itemId),
        cancel_source: source,
    })
}

/**
 * The message's place among the user's messages, counted from the end of the thread: 1 is the last one. The
 * same rule as `position_from_end` on the tasks backend. Null when the message is not in the thread.
 */
export function positionFromEnd(threadItems: ThreadItem[], itemId: string): number | null {
    const humanIds = threadItems.filter((item) => item.type === 'human_message').map((item) => item.id)
    const position = humanIds.indexOf(itemId)
    return position === -1 ? null : humanIds.length - position
}

export const EDIT_BLOCKED_REASONS = {
    slack: "Messages in chats started from Slack can't be edited",
    command: "Commands can't be edited",
    beforeClear: "Messages before /clear can't be edited",
    otherOpen: 'Finish the edit you have open first',
    composerPaused: 'Save or cancel your edit first',
    waitingAnswer: 'Answer the waiting question or approval first',
    queued: 'Wait for your queued messages to send',
    replying: 'Wait for the reply to finish',
} as const

export interface RunEditState {
    startedFromSlack: boolean
    waitingForAnswer: boolean
    queuedMessageCount: number
    runStatus: RunStatus | null
    turnComplete: boolean
}

/**
 * Why no message in the run can be edited right now, or null when they can. A finished run takes edits, and so
 * does a live one between turns, which the server ends first. Every reason but Slack clears by itself.
 */
export function runEditBlockedReason(state: RunEditState): string | null {
    if (state.startedFromSlack) {
        return EDIT_BLOCKED_REASONS.slack
    }
    if (state.waitingForAnswer) {
        return EDIT_BLOCKED_REASONS.waitingAnswer
    }
    if (state.queuedMessageCount > 0) {
        return EDIT_BLOCKED_REASONS.queued
    }
    if (state.runStatus === null || (!isTerminalRunStatus(state.runStatus) && !state.turnComplete)) {
        return EDIT_BLOCKED_REASONS.replying
    }
    return null
}

/**
 * Why each of the user's messages can never be edited, by item id. A resume keeps only the turns after the last
 * `/clear`, so earlier messages are out of reach. A compaction keeps the turns, so it blocks nothing.
 */
/**
 * Why one message's edit button is disabled, or undefined when it can be pressed. A reason that never clears
 * comes first, then an editor already open on another message, then the run-wide reason.
 */
export function editButtonDisabledReason(
    itemId: string,
    {
        messageReasons,
        runReason,
        editingMessageId,
    }: { messageReasons: Record<string, string>; runReason: string | null; editingMessageId: string | null }
): string | undefined {
    if (messageReasons[itemId]) {
        return messageReasons[itemId]
    }
    if (editingMessageId !== null && editingMessageId !== itemId) {
        return EDIT_BLOCKED_REASONS.otherOpen
    }
    return runReason ?? undefined
}

export function messageEditBlockedReasons(threadItems: ThreadItem[]): Record<string, string> {
    const lastClear = threadItems.findLastIndex((item) => item.type === 'conversation_cleared')
    const reasons: Record<string, string> = {}
    threadItems.forEach((item, position) => {
        if (item.type !== 'human_message') {
            return
        }
        if (startsWithAgentCommand(userMessageDisplayText(item.text ?? ''))) {
            reasons[item.id] = EDIT_BLOCKED_REASONS.command
        } else if (position < lastClear) {
            reasons[item.id] = EDIT_BLOCKED_REASONS.beforeClear
        }
    })
    return reasons
}

export const messageEditLogic = kea<messageEditLogicType>([
    props({} as MessageEditLogicProps),
    key((props) => props.streamKey),
    path((key) => ['products', 'posthog_ai', 'frontend', 'logics', 'messageEditLogic', key]),
    connect((props: MessageEditLogicProps) => ({
        values: [
            featureFlagLogic,
            ['featureFlags'],
            runStreamLogic({ streamKey: props.streamKey }),
            [
                'bootstrappedRunId',
                'bootstrappedTaskId',
                'currentProjectId',
                'currentRunStatus',
                'pendingPermissionRequest',
                'threadItems',
                'turnComplete',
            ],
        ],
    })),
    actions({
        startEdit: (item: ThreadItem) => ({ item }),
        /** Internal: opens the editor once `startEdit` has checked that no other editor is open. */
        openEditor: (item: ThreadItem) => ({ item }),
        setDraft: (draft: string) => ({ draft }),
        cancelEdit: (source: MessageEditCancelSource = 'button') => ({ source }),
        saveEdit: (item: ThreadItem) => ({ item }),
        saveEditSuccess: true,
        saveEditFailure: (error: string) => ({ error }),
        /** Set by the host, which knows the task and the composer. Kept in state, not props, so selectors see it. */
        setEditContext: (startedFromSlack: boolean, queuedMessageCount: number) => ({
            startedFromSlack,
            queuedMessageCount,
        }),
        /** Internal: the preview's count for the open editor, or null when it could not be loaded. */
        setRemovedMessageCount: (count: number | null, changesProject: boolean = false) => ({
            count,
            changesProject,
        }),
    }),
    reducers({
        startedFromSlack: [false, { setEditContext: (_, { startedFromSlack }) => startedFromSlack }],
        queuedMessageCount: [0, { setEditContext: (_, { queuedMessageCount }) => queuedMessageCount }],
        editingMessageId: [
            null as string | null,
            {
                openEditor: (_, { item }) => item.id,
                cancelEdit: () => null,
                saveEditSuccess: () => null,
            },
        ],
        draft: [
            '',
            {
                openEditor: (_, { item }) => item.text ?? '',
                setDraft: (_, { draft }) => draft,
                cancelEdit: () => '',
                saveEditSuccess: () => '',
            },
        ],
        removedMessageCount: [
            null as number | null,
            {
                openEditor: () => null,
                setRemovedMessageCount: (_, { count }) => count,
                cancelEdit: () => null,
                saveEditSuccess: () => null,
            },
        ],
        removedTurnsChangeProject: [
            false,
            {
                openEditor: () => false,
                setRemovedMessageCount: (_, { changesProject }) => changesProject,
                cancelEdit: () => false,
                saveEditSuccess: () => false,
            },
        ],
        removedMessageCountLoading: [
            false,
            {
                openEditor: () => true,
                setRemovedMessageCount: () => false,
                cancelEdit: () => false,
                saveEditSuccess: () => false,
            },
        ],
        saving: [
            false,
            {
                saveEdit: () => true,
                saveEditSuccess: () => false,
                saveEditFailure: () => false,
            },
        ],
        saveError: [
            null as string | null,
            {
                openEditor: () => null,
                cancelEdit: () => null,
                saveEdit: () => null,
                saveEditFailure: (_, { error }) => error,
            },
        ],
    }),
    selectors({
        editingEnabled: [
            (s) => [s.featureFlags, s.bootstrappedTaskId, s.bootstrappedRunId],
            (featureFlags: FeatureFlagsSet, taskId: string | null, runId: string | null): boolean =>
                !!featureFlags[FEATURE_FLAGS.PHAI_EDIT_MESSAGES] && !!taskId && !!runId,
        ],
        runEditBlockedReason: [
            (s) => [
                s.startedFromSlack,
                s.pendingPermissionRequest,
                s.queuedMessageCount,
                s.currentRunStatus,
                s.turnComplete,
            ],
            (
                startedFromSlack: boolean,
                pendingPermissionRequest: PermissionRequestRecord | null,
                queuedMessageCount: number,
                currentRunStatus: RunStatus | null,
                turnComplete: boolean
            ): string | null =>
                runEditBlockedReason({
                    startedFromSlack,
                    waitingForAnswer: pendingPermissionRequest !== null,
                    queuedMessageCount,
                    runStatus: currentRunStatus,
                    turnComplete,
                }),
        ],
        messageEditBlockedReasons: [
            (s) => [s.threadItems],
            (threadItems: ThreadItem[]): Record<string, string> => messageEditBlockedReasons(threadItems),
        ],
    }),
    listeners(({ actions, values, props, selectors }) => ({
        cancelEdit: ({ source }, __, ___, previousState) => {
            const itemId = selectors.editingMessageId(previousState)
            if (itemId === null) {
                return
            }
            captureEditCancelled(
                {
                    taskId: values.bootstrappedTaskId,
                    runId: values.bootstrappedRunId,
                    removedMessageCount: selectors.removedMessageCount(previousState),
                    removedTurnsChangeProject: selectors.removedTurnsChangeProject(previousState),
                    threadItems: values.threadItems,
                    itemId,
                },
                source
            )
        },
        // One editor at a time: a second one would replace the open draft and lose its text.
        startEdit: ({ item }) => {
            if (values.editingMessageId === null) {
                actions.openEditor(item)
            }
        },
        // The thread often holds only the tail of a long log, so only the server can count what the edit removes.
        openEditor: async ({ item }) => {
            const { bootstrappedTaskId: taskId, bootstrappedRunId: runId, currentProjectId: projectId } = values
            if (!item.logAddress || !taskId || !runId || projectId === null) {
                actions.setRemovedMessageCount(null)
                return
            }
            let count: number | null = null
            let changesProject = false
            try {
                const preview = await tasksRunsEditMessagePreviewCreate(String(projectId), taskId, runId, {
                    address: { run_id: item.logAddress.runId, index: item.logAddress.index },
                    original_text: item.text ?? '',
                })
                count = preview.removed_message_count
                changesProject = preview.removed_turns_change_project === true
            } catch {
                count = null
            }
            // A slow answer for an editor that has since closed, or moved to another message, is dropped.
            if (values.editingMessageId === item.id) {
                actions.setRemovedMessageCount(count, changesProject)
            }
        },
        saveEdit: async ({ item }) => {
            const taskId = values.bootstrappedTaskId
            const runId = values.bootstrappedRunId
            const projectId = values.currentProjectId
            const text = values.draft.trim()
            if (!item.logAddress || !taskId || !runId || projectId === null || !text) {
                actions.saveEditFailure(SAVE_FAILED_MESSAGE)
                return
            }
            try {
                const { run } = await tasksRunsEditMessageCreate(String(projectId), taskId, runId, {
                    address: { run_id: item.logAddress.runId, index: item.logAddress.index },
                    original_text: item.text ?? '',
                    text,
                })
                actions.saveEditSuccess()
                runStreamLogic({ streamKey: props.streamKey }).actions.attachEditedRun(taskId, run, text)
                props.onRunStarted?.(run.id, { run, streamKey: props.streamKey, draft: '' })
            } catch (error) {
                actions.saveEditFailure(editSaveErrorMessage(error))
            }
        },
    })),
    // Leaving the chat drops an open editor without `cancelEdit`, and listeners no longer run here, so this captures
    // directly. A save in flight already ends in saved or failed. Closing the tab is best effort through posthog-js.
    beforeUnmount(({ values }) => {
        if (values.editingMessageId !== null && !values.saving) {
            captureEditCancelled(
                {
                    taskId: values.bootstrappedTaskId,
                    runId: values.bootstrappedRunId,
                    removedMessageCount: values.removedMessageCount,
                    removedTurnsChangeProject: values.removedTurnsChangeProject,
                    threadItems: values.threadItems,
                    itemId: values.editingMessageId,
                },
                'left_page'
            )
        }
    }),
])
